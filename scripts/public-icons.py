#!/usr/bin/env python3
"""Bootstrap Icons for the customer pages, cut down to the icons they use.

The customer pages (layouts/public: pay links, payment results, tickets,
events, places, legal) used the whole Bootstrap Icons font from jsDelivr: a
render-blocking stylesheet on another domain plus a 130 KB font for about 60
icons. This writes a subset served from this server instead:

    public/fonts/bootstrap-icons/public.css
    public/fonts/bootstrap-icons/bootstrap-icons-<hash>.woff2   (~10 KB)

Icons are collected from the views in VIEW_PATHS: every bi-<name> class, and
the quoted names inside bi-{{ ... }} expressions. tests/Feature/PublicPageAssetsTest
fails when a public view uses an icon missing here; then run again:

    npm pack bootstrap-icons@1.11.3 && tar -xzf bootstrap-icons-1.11.3.tgz
    pip install fonttools brotli
    python3 scripts/public-icons.py package      # the extracted package folder

Bootstrap Icons: MIT License.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
VIEWS = ROOT / "resources" / "views"
# Same list as PublicPageAssetsTest::VIEW_PATHS.
VIEW_PATHS = ["layouts/public.blade.php", "partials", "payment", "public", "visitor", "components/admin/money.blade.php"]
OUT = ROOT / "public" / "fonts" / "bootstrap-icons"

ICON = re.compile(r"\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)")
DYNAMIC = re.compile(r"\bbi-\{\{(.*?)\}\}", re.S)
QUOTED = re.compile(r"""['"]([a-z0-9]+(?:-[a-z0-9]+)*)['"]""")


def used_icons() -> set[str]:
    names: set[str] = set()
    for rel in VIEW_PATHS:
        path = VIEWS / rel
        files = [path] if path.is_file() else sorted(path.rglob("*.blade.php"))
        for file in files:
            text = file.read_text(encoding="utf-8")
            names.update(ICON.findall(text))
            for expr in DYNAMIC.findall(text):
                names.update(QUOTED.findall(expr))
    return names


def main(package: Path) -> None:
    font_dir = package / "font"
    codepoints: dict[str, int] = json.loads((font_dir / "bootstrap-icons.json").read_text())
    css = (font_dir / "bootstrap-icons.css").read_text()
    version = re.search(r"Bootstrap Icons v([\d.]+)", css).group(1)

    names = used_icons()
    unknown = sorted(n for n in names if n not in codepoints)
    if unknown:
        sys.exit(f"Not Bootstrap Icons {version} icons: {', '.join(unknown)}")
    names = sorted(names)

    font = TTFont(font_dir / "fonts" / "bootstrap-icons.woff2")
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[n] for n in names])
    subsetter.subset(font)
    font.flavor = "woff2"

    OUT.mkdir(parents=True, exist_ok=True)
    tmp = OUT / "subset.tmp"
    font.save(tmp)
    digest = hashlib.sha256(tmp.read_bytes()).hexdigest()[:12]
    woff2 = OUT / f"bootstrap-icons-{digest}.woff2"
    for old in OUT.glob("bootstrap-icons-*.woff2"):
        if old != woff2:
            old.unlink()
    tmp.replace(woff2)

    # The base rule (.bi::before, [class^="bi-"]::before ...) as in the original.
    base = re.search(r'\.bi::before,\s*\[class\^="bi-"\]::before,\s*\[class\*=" bi-"\]::before\s*\{.*?\}', css, re.S).group(0)
    lines = [
        f"/* Bootstrap Icons v{version} (MIT), only the {len(names)} icons the customer pages use.",
        "   Generated by scripts/public-icons.py; do not edit. */",
        "@font-face {",
        '  font-display: block;',
        '  font-family: "bootstrap-icons";',
        f'  src: url("{woff2.name}") format("woff2");',
        "}",
        base,
    ]
    lines += [f'.bi-{n}::before {{ content: "\\{codepoints[n]:x}"; }}' for n in names]
    (OUT / "public.css").write_text("\n".join(lines) + "\n")
    print(f"{len(names)} icons, {woff2.stat().st_size // 1024} KB -> {woff2.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: python3 scripts/public-icons.py <extracted bootstrap-icons package folder>")
    main(Path(sys.argv[1]))
